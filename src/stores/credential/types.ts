// ─── Models ───────────────────────────────────────────────────────────

/** Credential as returned by the API; never contains secret values. */
export interface Credential {
  id: number
  name: string
  description?: string | null
  type: CredentialType
  kind: CredentialKind
  platform: CredentialPlatform
  status: CredentialStatus
  statusMessage?: string | null
  /** Non-secret display facts: username, phone, masked key… */
  metadata: Record<string, string>
  /** Number of workflow nodes using the credential. */
  usageCount: number
  lastCheckedAt?: string | null
  createdAt: string
  updatedAt?: string | null
}

export interface FormFieldOption {
  value: string
  label: string
}

/** One input of a credential form, generated by the backend from the data record. */
export interface FormFieldSchema {
  key: string
  label: string
  type: FormFieldType
  required: boolean
  secret: boolean
  hint?: string | null
  placeholder?: string | null
  defaultValue?: string | null
  options: FormFieldOption[]
  /** Show only when another field has the given value. */
  visibleWhen?: { field: string; value: string } | null
}

/** Descriptor of a credential type: drives pickers and forms. */
export interface CredentialTypeDescriptor {
  type: CredentialType
  kind: CredentialKind
  platform: CredentialPlatform
  displayName: string
  description: string
  setupMode: SetupMode
  available: boolean
  testable: boolean
  /** Data fields for FORM types, start parameters for INTERACTIVE types. */
  fields: FormFieldSchema[]
}

export interface CredentialSummary {
  counts: Record<CredentialKind, number>
  total: number
}

export interface CredentialTestResult {
  success: boolean
  supported: boolean
  message: string
  credential: Credential
}

/** Backend page; structurally a SlbPage so it plugs into SlbSelect/SlbTable. */
export interface CredentialPage extends SlbPage<Credential> {
  items: Credential[]
  total: number
  page: number
  pageSize: number
  hasMore: boolean
}

export type CredentialSortKey = 'name' | 'type' | 'status' | 'createdAt' | 'updatedAt'

export interface CredentialQuery {
  kind?: CredentialKind
  types?: CredentialType[]
  status?: CredentialStatus
  search?: string
  /** 1-based. */
  page: number
  pageSize: number
  sort?: CredentialSortKey
  direction?: 'asc' | 'desc'
}

export type FormValues = Record<string, string | number | boolean | null>

export interface CredentialCreateRequest {
  type: CredentialType
  name?: string
  description?: string
  data: FormValues
}

export interface CredentialUpdateRequest {
  name: string
  description?: string
  /** Changed values; blank secret fields keep the stored value. */
  data?: FormValues
}

// ─── Interactive account connection ───────────────────────────────────

export enum ConnectEventType {
  STATUS = 'STATUS',
  QR_CODE = 'QR_CODE',
  /** A code the user enters on their phone (WhatsApp's "Link with phone number instead"). */
  PAIRING_CODE = 'PAIRING_CODE',
  /** A page the user opens to authorize the app (OAuth, e.g. an XChat bot). */
  OPEN_URL = 'OPEN_URL',
  INPUT_REQUIRED = 'INPUT_REQUIRED',
  SUCCESS = 'SUCCESS',
  ERROR = 'ERROR',
}

export enum ConnectInput {
  CODE = 'CODE',
  PASSWORD = 'PASSWORD',
}

/** Which XChat PIN a PASSWORD input asks for (`payload.pin`); absent for other passwords. */
export enum ConnectPin {
  /** The PIN the account already has: its XChat keys are recovered with it. */
  UNLOCK = 'UNLOCK',
  /** A new PIN: the account's first XChat keys are backed up under it. */
  SET_UP = 'SET_UP',
}

export enum QrFormat {
  /** Raw link to encode client-side. */
  LINK = 'LINK',
  /** Ready data:image URL. */
  IMAGE = 'IMAGE',
}

interface ConnectEventBase<T extends ConnectEventType, P> {
  type: T
  message: string
  payload: P
}

/** Discriminated union on `type`: `switch (event.type)` narrows the payload. */
export type ConnectEvent =
  | ConnectEventBase<ConnectEventType.STATUS, Record<string, never>>
  | ConnectEventBase<ConnectEventType.QR_CODE, { value: string; format: QrFormat }>
  | ConnectEventBase<ConnectEventType.PAIRING_CODE, { code: string }>
  | ConnectEventBase<ConnectEventType.OPEN_URL, { url: string }>
  | ConnectEventBase<
      ConnectEventType.INPUT_REQUIRED,
      { input: ConnectInput; hint?: string; timeout?: number; error?: string; pin?: ConnectPin }
    >
  | ConnectEventBase<ConnectEventType.SUCCESS, { credential: Credential }>
  | ConnectEventBase<ConnectEventType.ERROR, Record<string, never>>

export interface ConnectStartRequest {
  type: CredentialType
  name?: string
  params: FormValues
}

