import { PropertyType, type NodeTypeDescriptor, type PropertyDescriptor } from './descriptor'

/**
 * Generates TypeScript parameter types from node type descriptors (`npm run gen:node-types`), so the editor
 * cannot drift from the Java parameter records. Only types with schema properties are emitted; legacy nodes
 * with hand-written panels have none.
 */

const HEADER = `// Generated by \`npm run gen:node-types\` from the backend node type descriptors. Do not edit.

/** A parameter value with {{ }} expressions, resolved per item at run time. */
export type Expression = \`\${string}{{\${string}}}\${string}\`
`

/** `telegram.accountTrigger@1` → `TelegramAccountTriggerV1Params` */
export function paramsTypeName(descriptor: Pick<NodeTypeDescriptor, 'name' | 'version'>): string {
  const words = descriptor.name.split(/[^A-Za-z0-9]+/).filter(Boolean)
  return `${words.map((w) => w[0]!.toUpperCase() + w.slice(1)).join('')}V${descriptor.version}Params`
}

const literal = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const propertyKey = (name: string): string => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : literal(name))

function valueType(property: PropertyDescriptor, indent: string): string {
  switch (property.type) {
    case PropertyType.STRING:
      return 'string'
    case PropertyType.NUMBER:
      return 'number'
    case PropertyType.BOOLEAN:
      return 'boolean'
    case PropertyType.OPTIONS:
      return property.options.length ? property.options.map((o) => literal(o.value)).join(' | ') : 'string'
    case PropertyType.MULTI_OPTIONS:
      return `Array<${property.options.length ? property.options.map((o) => literal(o.value)).join(' | ') : 'string'}>`
    case PropertyType.COLLECTION:
      return objectType(property.children, indent)
    case PropertyType.FIXED_COLLECTION:
      return `Array<${objectType(property.children, indent)}>`
    case PropertyType.JSON:
    case PropertyType.AUTO:
      return 'unknown'
  }
}

/** A required field shown only under conditions (another operation's field) may still be absent. */
const isAlwaysPresent = (property: PropertyDescriptor): boolean =>
  property.required && property.show.length === 0 && property.hide.length === 0

function objectType(properties: readonly PropertyDescriptor[], indent: string): string {
  if (!properties.length) return 'Record<string, never>'
  const inner = `${indent}  `
  const lines = properties.map((property) => {
    const base = valueType(property, inner)
    // Strings already admit templates; other types take one in place of the value.
    const type = property.expression && property.type !== PropertyType.STRING ? `${base} | Expression` : base
    const doc = property.description ? `${inner}/** ${property.displayName}: ${property.description} */\n` : `${inner}/** ${property.displayName} */\n`
    return `${doc}${inner}${propertyKey(property.name)}${isAlwaysPresent(property) ? '' : '?'}: ${type}`
  })
  return `{\n${lines.join('\n')}\n${indent}}`
}

/**
 * @param descriptors node types as served by `GET /api/v1/node-types`
 * @returns source of `src/generated/node-types.ts`
 */
export function generateNodeTypes(descriptors: readonly NodeTypeDescriptor[]): string {
  const typed = [...descriptors].filter((d) => d.properties.length).sort((a, b) => a.key.localeCompare(b.key))
  const interfaces = typed.map(
    (d) => `/** ${d.displayName} (\`${d.key}\`) */\nexport interface ${paramsTypeName(d)} ${objectType(d.properties, '')}\n`,
  )
  const map = typed.map((d) => `  ${literal(d.key)}: ${paramsTypeName(d)}`)
  return [
    HEADER,
    ...interfaces,
    `/** Parameters of each schema-driven node type, by \`name@version\`. */\nexport interface NodeParamsMap {\n${map.join('\n')}\n}\n`,
    `export type SchemaNodeTypeKey = keyof NodeParamsMap\n`,
  ].join('\n')
}
